import Foundation

/// Перетаскивание в зеркало и вставка: сеанс перетаскивания нельзя «переложить» на окно другого дисплея
/// (его ведёт WindowServer за настоящим курсором), поэтому брошенное в зеркало кладётся во временный буфер
/// и вставляется в программу как ⌘V. После вставки буфер пользователя возвращается.
public enum DropRoute: Equatable, Sendable {
    /// Картинки-файлы: в буфер и файл, и PNG — Chromium (Claude) вставляет картинку из `public.png`.
    case imageFiles([URL])
    /// Прочие файлы: ссылка на файл (`public.file-url`), как после ⌘C в Finder.
    case files([URL])
    /// Картинка без файла (из браузера, Превью): данные как есть.
    case imageData(type: String)
    case text(String)
    case unsupported
}

public enum DropBridge {
    static let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "gif", "heic", "heif", "webp", "tif", "tiff", "bmp"]
    static let imageTypes = ["public.png", "public.tiff", "public.jpeg", "public.heic"]

    /// Выбор пути по содержимому перетаскивания/буфера. Файлы важнее картинки (у файла из Finder есть и значок-картинка).
    public static func route(fileURLs: [URL], types: [String], text: String?) -> DropRoute {
        let files = fileURLs.filter(\.isFileURL)
        if !files.isEmpty {
            return files.allSatisfy({ imageExtensions.contains($0.pathExtension.lowercased()) }) ? .imageFiles(files) : .files(files)
        }
        if let type = imageTypes.first(where: types.contains) { return .imageData(type: type) }
        if let text, !text.isEmpty { return .text(text) }
        return .unsupported
    }

    /// Пометки для менеджеров буфера (http://nspasteboard.org): временное и скрытое содержимое не попадает в историю.
    public static let transientMarkers = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"]
}

/// Буфер обмена, как его видит подмена: снимок, замена, счётчик изменений. В программе — `NSPasteboard.general`.
public protocol PasteboardStore: AnyObject {
    var changeCount: Int { get }
    func snapshot() -> [[String: Data]]
    /// Заменить содержимое; вернуть новый `changeCount`.
    @discardableResult func replace(with items: [[String: Data]]) -> Int
}

/// Временная подмена буфера на время вставки в программу на скрытом дисплее.
public final class ClipboardSwap {
    private let store: PasteboardStore
    private var saved: [[String: Data]]?
    private var ownChange: Int?

    public init(store: PasteboardStore) {
        self.store = store
    }

    /// Сохранить буфер пользователя и положить свои данные (с пометками «временное»).
    public func begin(with items: [[String: Data]]) {
        if saved == nil { saved = store.snapshot() }
        let marked = items.enumerated().map { index, item -> [String: Data] in
            guard index == 0 else { return item }
            var item = item
            for marker in DropBridge.transientMarkers { item[marker] = Data() }
            return item
        }
        ownChange = store.replace(with: marked)
    }

    /// Вернуть буфер пользователя, если с момента подмены в буфер никто не писал.
    /// Если писали (пользователь успел что-то скопировать), его новое содержимое не трогаем.
    @discardableResult public func restore() -> Bool {
        defer { saved = nil; ownChange = nil }
        guard let saved, let ownChange, store.changeCount == ownChange else { return false }
        store.replace(with: saved)
        return true
    }

    public var isActive: Bool { saved != nil }
}
